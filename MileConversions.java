public class MileConversions {
     public static void main(String[] args) {

        int inchesInMile = 63360;
        int feetInMile = 5280;
        int yardsInMile = 1760;

        int miles = 1;

        System.out.println(miles + " mile(s) in inches: " + miles * inchesInMile);
        System.out.println(miles + " mile(s) in feet: " + miles * feetInMile);
        System.out.println(miles + " mile(s) in yards: " + miles * yardsInMile);
    }
}
